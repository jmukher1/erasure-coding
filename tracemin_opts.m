function opts = tracemin_opts(user)
% default TraceMin options, overridden by the fields of user. 

    d = struct( ...
        'blockFactor',  2, ...
        'shiftMode',    'common', ...
        'shiftTol',     1e-2, ...
        'shiftSafety',  1.1, ...
        'shiftFloor',   1e-8, ...
        'refactorGain', 0.9, ...
        'maxRefactor',  8, ...
        'faultReset',   'random', ...
        'lockTol',      1e-12, ...
        'stagnWindow',  25, ...
        'stagnFactor',  0.9, ...
        'coding',       'interleaved', ...
        'dropTol',      1e-12, ...
        'verbose',      1, ...
        'seed',         []);

    if nargin < 1 || isempty(user)
        opts = d;
        return;
    end
    if ~isstruct(user)
        error('tracemin_opts:badInput', 'opts override must be a struct.');
    end

    opts = d;
    f = fieldnames(user);
    for i = 1:numel(f)
        if ~isfield(d, f{i})
            error('tracemin_opts:unknownField', ...
                  'Unknown option "%s". Valid fields: %s', ...
                  f{i}, strjoin(fieldnames(d)', ', '));
        end
        opts.(f{i}) = user.(f{i});
    end

    if ~ismember(opts.coding, {'default', 'interleaved'})
        error('tracemin_opts:badCoding', 'coding must be ''default'' or ''interleaved''.');
    end
    if ~ismember(opts.faultReset, {'random', 'zero', 'jacobi'})
        error('tracemin_opts:badFaultReset', 'faultReset must be ''random'', ''zero'' or ''jacobi''.');
    end
    if ~ismember(opts.shiftMode, {'common', 'none'})
        error('tracemin_opts:badShiftMode', 'shiftMode must be ''common'' or ''none''.');
    end
    if opts.blockFactor < 1
        error('tracemin_opts:badBlock', 'blockFactor must be >= 1.');
    end
end
